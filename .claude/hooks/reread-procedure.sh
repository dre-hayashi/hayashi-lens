#!/bin/bash
# 毎ターン、CLAUDE.md の「オーナーの FB を理解する手順」と「やってはいけないこと」を読み直させる。
# 自覚に頼らず、ターンの先頭で必ず目に入る形にする。
f="$(git rev-parse --show-toplevel 2>/dev/null)/CLAUDE.md"
[ -f "$f" ] || exit 0
echo "【ターン開始前の照合。返答を出す前に、以下に通っているかを確かめ、通っていなければ出さない】"
awk '/^## やってはいけないこと/,/^## オーナーの FB を理解する手順/' "$f" | sed '$d'
awk '/^## オーナーの FB を理解する手順/,/^## うまくいったやり方/' "$f" | sed '$d'
echo "【FB を扱う返答は、手順1〜3の見出しと、各コメントに四段以上の「なぜ」の鎖を根まで書いたものだけを出す。鎖が作れない項目は「鎖が作れない」と書く。書き込み（Google ドキュメント、git push）はオーナーの指示があった項目だけ】"
