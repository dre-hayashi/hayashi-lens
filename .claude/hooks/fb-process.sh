#!/bin/bash
# UserPromptSubmit フック：オーナーからスキルへの指摘・課題の提示・スキルに関わる情報の FB や共有を受けたら、
# 5Why を含む所定の確認を、返答やスキルの変更より先に行うことを義務づける。あわせて、オーナーへの書き方の注意を毎回出す。
# 本人の指示（2026-11-10）：「同じ問題が頻発しているので、UserPromptSubmit の Hook 作って対処しなさい」
# 「鎖だとか段だとか道だとか、そんな説明は日本人はしない。この指摘も全く正されないので、Hook に注意事項として含めるように」
# 中身の判定を機械に任せると漏れるので、毎回出す。当てはまるかどうかは、メッセージを読んで最初に確かめさせる。
cat <<'EOF'
【オーナーのメッセージを読んだら、最初にやること。返答も、スキルの変更も、これを終えてから】
このメッセージに、次のどれかが入っているかを確かめる。
- スキルの動きや中身への指摘
- スキルの課題の提示
- スキルに関わる情報の FB や共有（ケースへの判断、資料、考え方）
一つでも入っていれば、下の確認を上から順に全部行う。指摘を受けた直後こそ行う。その場で直した形を先に見せない。

1. 受け取った内容を一つずつに分ける。事例への判断か、スキルの動きや中身への指摘か、Claude の仕事の仕方への指摘か。
2. スキルに関わるもの一つずつについて、オーナーがどの立場、どの役割でそれを言っているかを書く。
3. 5Why を行う。一つの判断から始める。「なぜ、そう判断するのか」に、オーナーの立場と役割に立って、推し量って答える。出た答えに、また「なぜ」を問う。途中で別の言葉への問いに乗り換えない。オーナーの別の言葉を引いて答えにしない。
4. 行き着いた所を書く。どの立場で、何を見て、なぜそう判断するか。
5. 別の持ち込み（別の場面、別の役割、別の資料）に当てて、オーナーが何と言うかを自分で言えるかを確かめる。言えたら、記録（docs/casestudies.md）にある別の場面の言葉と合うかを確かめる。
6. 同じ判断がスキルに既に入っているかを確かめる。入っているのに働いていないなら、どの手順がそれを使っていないかを、実行の記録で確かめる。
7. スキルをどう直すかを考え抜く。
8. 3〜7 でやったことを、返答の中でオーナーに見せる。推し量った答えには「推察」と付ける。
9. オーナーの「合っている／合っていない」を得るまで、スキルには入れない。
10. スキルの中身を取り消す・戻すときは、消す前に中身を一つずつ比べる。必要なものは、残すか、戻す。戻した先（どのファイルの、どの文か）をオーナーに見せる。理由をつけて問題を残さない。

【オーナーへの書き方。毎回】
普通の日本語で書く。自分で作った言い回しや、スキルの内部の呼び名を、説明に使わない。
- 使わない語：鎖、段、道、道筋、線、核、土台、面、見立て、物差し、辿り方。番号の付いた内部の呼び名も使わない。
- 言い換える：「なぜを繰り返して分かったこと」「三つ目の手順（役割と状況から責任を導く手順）」「判断の基準」「前提」。ファイルは、名前と、何が書いてあるファイルかを添える。
- 中身の分からない言い方をしない（「足すのではなく直す」など）。何を、どこで、どう変えるかを書く。
- 出す前に、返答を頭から読み直し、日本人が普通に書く文になっているかを確かめる。
EOF
